"""Process one uploaded call for the web app's live upload (web/app/run-api, POST /calls).

    python web/scripts/process_upload.py <audio.wav> <call_id> <upload_dir>

Runs pipeline.process_call on the audio and prints one JSON line per ProcessingEvent on stdout (flushed), then a
final {"event": "result", ...} line. Everything the pipeline writes goes under <upload_dir> (its own artifacts/ and
out/), so the shared artifacts and the recorded runs are never touched. Before the run it checks that the language
model answers; if not, it says so in plain words and the call still runs (extraction fails, the call ends as review).
The web app starts this with an argument array (no shell); the call id is generated by the app, never user text.
"""
from __future__ import annotations

import json
import os
import sys
import time
import urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

from pipeline import process_call  # noqa: E402
from pipeline.llm import load_env  # noqa: E402


def out(obj: dict) -> None:
    print(json.dumps(obj, ensure_ascii=False), flush=True)


def llm_reachable() -> tuple[bool, str]:
    base = (os.environ.get("LLM_BASE_URL") or "").rstrip("/")
    if not base:
        return False, "LLM_BASE_URL is not set"
    try:
        with urllib.request.urlopen(f"{base}/models", timeout=4) as r:       # noqa: S310 - local tunnel URL from .env
            return r.status == 200, f"HTTP {r.status}"
    except Exception as e:  # noqa: BLE001
        return False, type(e).__name__


def main() -> None:
    audio, call_id, upload_dir = sys.argv[1], sys.argv[2], Path(sys.argv[3])
    load_env()
    ok, why = llm_reachable()
    if not ok:
        out({"event": "notice", "call_id": call_id, "stage": "extract", "message": f"LLM not reachable ({why}): is the SSH tunnel to the model server up? The call will end as review."})
    t0 = time.time()
    res = process_call(audio, call_id, on_event=out, transcripts="asr", trigger=True,
                       artifacts_dir=upload_dir / "artifacts", out_dir=upload_dir / "out")
    out({"event": "result", "call_id": call_id, "decision": res.get("decision"), "elapsed_s": round(time.time() - t0, 1),
         "n_stage_errors": len(res.get("stage_errors") or [])})


if __name__ == "__main__":
    main()
